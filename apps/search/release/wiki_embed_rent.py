#!/usr/bin/env python3
"""Run wiki_embed_pod.py on ONE rented RunPod GPU through utility/judge-pod, collect the codes, terminate the pod.

    wiki_embed_rent.py run CHANGED.tsv.gz OUT_DIR --cap USD [--ttl MIN] [--gpu NAME] [--keep-repo]

Owner 2026-11-15: embedding on RunPod, hard cap $5 total (spend approval is per job; --cap is required). Steps:
  1. texts = wiki_ivf_delta.py texts (title. lead[:600], public Wikipedia text) + the recipe-check sample + the live codes of
     that sample go to a TEMPORARY PUBLIC Hugging Face dataset repo (token: .credentials/huggingface.token, never printed);
     no secret is ever sent to the pod;
  2. judge-pod.py up (price x ttl cannot pass --cap; the pod deletes itself after --ttl and a watchdog deletes it too);
  3. poll the pod's log until DONE or GATE-FAILED (the pod stops itself when its codes disagree with the live ones);
  4. download every shard, check sizes and sha256 against manifest.json, check the row count against the texts sent;
  5. judge-pod.py down, then GET /pods and require that no pod is left; delete the temporary repo.
Any error ends in step 5 (a `finally`). The ledger line (minutes, dollars) is printed and goes in the plan doc.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
POD = REPO / "utility" / "judge-pod" / "judge-pod.py"
IMAGE = "runpod/pytorch:2.4.0-py3.11-cuda12.4.1-devel-ubuntu22.04"
SAMPLE_TEXTS = Path("/home/owner/data/wf/recipe-orig.tsv.gz")      # buildbox's own wiki_texts rows of the 2,954-article sample
SAMPLE_CODES = Path("/home/owner/data/wf/rc15codes.json")          # their live rc15 codes (read from the release's ivf folder)


def log(m: str) -> None:
    print(f"[wiki-embed-rent {time.strftime('%H:%M:%S')}] {m}", flush=True)


def runpod_key() -> str:
    for c in (REPO / ".credentials" / "runpod.env", Path.home() / "code" / "m8server" / ".credentials" / "runpod.env"):
        if c.exists():
            for line in c.read_text().splitlines():
                if "RUNPOD_API_KEY" in line:
                    return line.split("=", 1)[1].strip().strip("\"'")
    sys.exit("no RUNPOD_API_KEY")


def pods() -> list:
    """The account's pods, through the same call judge-pod makes (REST, or GraphQL when rest.runpod.io does not resolve)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("judge_pod", POD)
    jp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(jp)
    s, d = jp.api("GET", "/pods")
    if s != 200 or not isinstance(d, list):
        raise RuntimeError(f"could not list pods: {s} {str(d)[:200]}")
    return d


def get(url: str, dest: Path | None = None):
    r = urllib.request.Request(url, headers={"User-Agent": "curl/8"})
    with urllib.request.urlopen(r, timeout=120) as resp:
        if dest is None:
            return resp.read()
        with open(dest, "wb") as f:
            while chunk := resp.read(1 << 22):
                f.write(chunk)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while c := f.read(1 << 22):
            h.update(c)
    return h.hexdigest()


def run(a) -> None:
    from huggingface_hub import HfApi
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    stage = out / "send"
    stage.mkdir(exist_ok=True)
    subprocess.run([sys.executable, str(HERE / "wiki_ivf_delta.py"), "texts", a.changed, str(stage / "texts.tsv.gz")], check=True)
    n_rows = sum(1 for _ in __import__("gzip").open(stage / "texts.tsv.gz", "rt", encoding="utf-8"))
    for src, name in ((SAMPLE_TEXTS, "sample-texts.tsv.gz"), (SAMPLE_CODES, "sample-codes.json"), (HERE / "wiki_embed_pod.py", "wiki_embed_pod.py")):
        (stage / name).write_bytes(src.read_bytes())
    token = Path(os.environ.get("HF_TOKEN_FILE", REPO / ".credentials" / "huggingface.token")).read_text().strip() \
        if (REPO / ".credentials" / "huggingface.token").exists() else Path("/home/owner/code/m8server/.credentials/huggingface.token").read_text().strip()
    api = HfApi(token=token)
    repo = f"logoutsearch/wiki-embed-tmp-{time.strftime('%Y%m%d%H%M')}"
    api.create_repo(repo, repo_type="dataset", private=False)
    pod_up = False
    try:
        for f in sorted(stage.iterdir()):
            api.upload_file(path_or_fileobj=str(f), path_in_repo=f.name, repo_id=repo, repo_type="dataset")
        base = f"https://huggingface.co/datasets/{repo}/resolve/main"
        recipe = {"about": "wiki embed (generated by wiki_embed_rent.py)", "image": IMAGE, "gpu": a.gpu, "cloud": "COMMUNITY", "disk_gb": 40,
                  "service_port": 8080, "health": "/", "preflight": "true",
                  "start": f"pip install -q sentence-transformers==5.1.1 einops && curl -fsSL {base}/wiki_embed_pod.py -o /root/embed.py && "
                           f"python3 /root/embed.py {base} /root/log/out"}
        rp = out / "recipe.json"
        rp.write_text(json.dumps(recipe))
        gpus = [g.strip() for g in a.gpu.split(",") if g.strip()]
        t_try, r = time.time(), None
        while True:                                   # supply comes and goes: every card in turn, then again for --wait-supply minutes
            for g in gpus:
                recipe["gpu"] = g
                rp.write_text(json.dumps(recipe))
                r = subprocess.run([sys.executable, str(POD), "up", str(rp), "--cap", str(a.cap), "--ttl", str(a.ttl), "--gpu", g], capture_output=True, text=True)
                if r.returncode == 0:
                    break
                log(f"{g}: {(r.stderr + r.stdout).strip()[-160:]}")
            if r.returncode == 0 or time.time() - t_try > a.wait_supply * 60:
                break
            time.sleep(45)
        log(r.stdout.strip().splitlines()[0] if r.stdout.strip() else r.stderr.strip())
        if r.returncode != 0:
            sys.exit("the pod did not start: " + r.stderr + r.stdout)
        pod_up = True
        cur = json.loads((Path.home() / ".cache" / "logout" / "pod-current.json").read_text())
        pbase = f"https://{cur['id']}-8081.proxy.runpod.net"
        t0, last = time.time(), ""
        while time.time() - t0 < a.ttl * 60:
            time.sleep(30)
            try:
                txt = get(pbase + "/out.txt").decode("utf-8", "replace")
            except Exception:
                continue
            tail = [l for l in txt.splitlines() if "wiki-embed-pod" in l][-1:] or [""]
            if tail[0] != last:
                last = tail[0]
                log(last)
            try:
                get(pbase + "/out/DONE")
                break
            except Exception:
                pass
            try:
                gate = get(pbase + "/out/GATE-FAILED").decode()
                sys.exit("the pod's gate failed: " + gate)
            except SystemExit:
                raise
            except Exception:
                pass
        else:
            sys.exit("the pod did not finish inside the ttl")
        man = json.loads(get(pbase + "/out/manifest.json"))
        if man["rows"] != n_rows:
            sys.exit(f"manifest says {man['rows']} rows, {n_rows} texts were sent")
        for s in man["shards"]:
            for kind in ("ids", "bits"):
                dest = out / f"{s['name']}.{kind}.npy"
                get(f"{pbase}/out/{s['name']}.{kind}.npy", dest)
                if sha256(dest) != s[f"{kind}_sha256"]:
                    sys.exit(f"{dest} does not match the manifest checksum")
        (out / "manifest.json").write_text(json.dumps(man, indent=1))
        log(f"downloaded {len(man['shards'])} shards, {man['rows']} rows, checksums match; gate {man['gate']}")
    finally:
        if pod_up:
            subprocess.run([sys.executable, str(POD), "down"], check=False)
        try:
            left = pods()
            log(f"pods left on the account: {len(left)} {[p.get('id') for p in left]}")
        except Exception as e:
            left = [{"id": "UNKNOWN"}]
            log(f"COULD NOT LIST PODS ({e}): check the RunPod console by hand")
        if not a.keep_repo:
            try:
                api.delete_repo(repo, repo_type="dataset")
                log(f"temporary repo {repo} deleted")
            except Exception as e:
                log(f"could not delete {repo}: {e}")
        subprocess.run([sys.executable, str(POD), "ledger"], check=False)
        if left:
            sys.exit("A POD IS STILL RUNNING: terminate it by hand")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run"); r.add_argument("changed"); r.add_argument("out")
    r.add_argument("--cap", type=float, required=True); r.add_argument("--ttl", type=int, default=90)
    r.add_argument("--gpu", default="NVIDIA GeForce RTX 4090", help="one card or a comma list tried in order")
    r.add_argument("--wait-supply", type=int, default=30, help="minutes to keep retrying when no card has supply"); r.add_argument("--keep-repo", action="store_true")
    run(ap.parse_args())


if __name__ == "__main__":
    main()
